package main

import "unicode"

// displayWidth is the number of terminal columns s takes up: two for wide
// characters (CJK, most emoji), none for combining marks and other
// zero-width characters, one for everything else. That is close to what
// wcwidth(3) reports and enough to line up a column of event names.
func displayWidth(s string) int {
	n := 0
	for _, r := range s {
		switch {
		case unicode.In(r, unicode.Mn, unicode.Me, unicode.Cf):
		case unicode.Is(wide, r):
			n += 2
		default:
			n++
		}
	}
	return n
}

